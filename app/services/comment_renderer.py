"""Render only the saved human-facing review fields, never checkpoint internals."""

import html
import re

from app.core.config import Settings
from app.core.exceptions import CommentUnavailableError
from app.schemas.publication import CommentReview
from app.schemas.review import AgentType, Recommendation, ReviewStatus, Severity

SECTIONS = (
    (AgentType.SECURITY, "🔐 Security"),
    (AgentType.TESTING, "🧪 Testing"),
    (AgentType.QUALITY, "🧹 Code Quality"),
    (AgentType.DOCUMENTATION, "📚 Documentation"),
)
WEIGHTS = {Severity.CRITICAL: 4, Severity.HIGH: 3, Severity.MEDIUM: 2, Severity.LOW: 1}


def plain(value: str, limit: int) -> str:
    value = "".join(char for char in value if char.isprintable() or char.isspace())
    value = re.sub(r"\s+", " ", value).strip()
    value = value[:limit] + ("…" if len(value) > limit else "")
    value = html.escape(value, quote=False).replace("@", "＠")
    return re.sub(r"([\\`*_{}\[\]()#+.!|~>-])", r"\\\1", value)


def code_span(value: str) -> str:
    value = "".join(char for char in value if char.isprintable() or char.isspace())
    value = re.sub(r"\s+", " ", value).strip().replace("@", "＠")
    value = value[:1024] + ("…" if len(value) > 1024 else "")
    longest = max((len(run) for run in re.findall(r"`+", value)), default=0)
    fence = "`" * (longest + 1)
    return f"{fence} {value} {fence}"


def review_marker(review: CommentReview) -> str:
    return f"<!-- ai-pr-review-agent:review={review.review_id}:head={review.head_sha.lower()} -->"


def render_comment(review: CommentReview, settings: Settings) -> str:
    if review.status not in {ReviewStatus.COMPLETED, ReviewStatus.PARTIAL}:
        raise CommentUnavailableError("Only completed or partial reviews have comments")
    if review.risk is None or review.recommendation is None or review.summary is None:
        raise CommentUnavailableError("Review outcome is incomplete")
    recommendation = review.recommendation
    if review.status == ReviewStatus.PARTIAL and recommendation == Recommendation.APPROVE:
        recommendation = Recommendation.COMMENT
    header = (
        "# 🤖 AI Pull Request Review\n\n"
        f"**Overall Risk:** {review.risk.value.title()}  \n"
        f"**Recommendation:** {recommendation.value.replace('_', ' ').title()}  \n"
        f"**Review status:** {review.status.value.title()}  \n"
        f"**Reviewed commit:** `{review.head_sha.lower()}`\n\n"
    )
    if review.mock_mode is True or (review.summary or "").startswith("[MOCK]"):
        header += "**Demo review:** predefined mock output; no model analysis was performed.\n\n"
    if review.status == ReviewStatus.PARTIAL:
        header += (
            "**Incomplete review:** some reviewers or supplied-code coverage were unavailable. "
            "This is not a complete approval.\n\n"
        )
    summary = "\n---\n\n**Summary**\n\n" + plain(review.summary, 1000) + "\n\n"
    footer = "\nGenerated by AI PR Review Agent.\n\n" + review_marker(review) + "\n"
    empty = (
        "No significant issues found."
        if review.status == ReviewStatus.COMPLETED
        else "No findings reported in the available results."
    )
    groups = {kind: [] for kind, _ in SECTIONS}
    findings = sorted(
        review.findings,
        key=lambda f: (
            -WEIGHTS[f.severity],
            -f.confidence,
            f.file_path,
            f.line_number or 0,
            f.title,
            f.agent_type.value,
        ),
    )

    def assemble() -> str:
        shown = sum(len(blocks) for blocks in groups.values())
        body = header
        for kind, title in SECTIONS:
            nothing_shown = (
                "Findings omitted here due to the comment size limit; see the stored review."
                if any(finding.agent_type == kind for finding in findings)
                else empty
            )
            body += (
                f"## {title}\n\n"
                + ("\n\n".join(groups[kind]) if groups[kind] else nothing_shown)
                + "\n\n"
            )
        noun = "finding" if len(findings) == 1 else "findings"
        body += summary + f"{len(findings)} actionable {noun}; {shown} shown."
        if shown < len(findings):
            body += (
                " Some findings were omitted to keep this comment within its size limit; "
                "consult the stored review for the full result."
            )
        return body + "\n" + footer

    for finding in findings[: settings.github_comment_max_findings]:
        location = finding.file_path + (f":{finding.line_number}" if finding.line_number else "")
        block = (
            f"### {finding.severity.value} — {plain(finding.title, 200)}\n\n"
            + code_span(location)
            + "\n\n"
            + plain(finding.description, 1100)
            + "\n\n**Suggestion:** "
            + plain(finding.suggestion, 1100)
        )
        groups[finding.agent_type].append(block)
        if len(assemble().encode("utf-8")) > settings.github_comment_max_bytes:
            groups[finding.agent_type].pop()
    body = assemble()
    if len(body.encode("utf-8")) > settings.github_comment_max_bytes:
        # A minimum-size comment must still fit multibyte summaries and all four sections.
        summary = (
            "\n---\n\n**Summary**\n\n"
            "Review completed; see the stored review for the full summary.\n\n"
        )
        body = assemble()
    if len(body.encode("utf-8")) > settings.github_comment_max_bytes:
        raise CommentUnavailableError("Comment could not fit the configured byte limit")
    return body
