"""Persist a clearly labeled synthetic review; no queue, GitHub, or LLM calls."""

import argparse
import asyncio
from pathlib import Path
from uuid import NAMESPACE_URL, uuid5

from app.core.config import get_settings
from app.db.repositories import ReviewRepository
from app.db.session import build_engine, build_session_factory
from app.schemas.github import PullRequestContext, PullRequestWebhook
from app.schemas.jobs import ReviewJob
from app.schemas.review import FindingInput, ReviewCompletion, ReviewStatus


async def seed(webhook: PullRequestWebhook) -> None:
    pr = webhook.pull_request
    job = ReviewJob(
        review_id=uuid5(NAMESPACE_URL, "ai-pr-review-agent/synthetic-demo-review"),
        delivery_id=uuid5(NAMESPACE_URL, "ai-pr-review-agent/synthetic-demo-delivery"),
        repository=webhook.repository.full_name,
        pr_number=pr.number,
        action="opened",
        base_sha=pr.base.sha,
        head_sha=pr.head.sha,
    )
    context = PullRequestContext(
        repository=job.repository,
        pr_number=job.pr_number,
        title=pr.title,
        description=pr.body or "",
        author=pr.user.login,
        base_branch=pr.base.ref,
        head_branch=pr.head.ref,
        base_sha=pr.base.sha,
        head_sha=pr.head.sha,
        head_repository=pr.head.repo.full_name if pr.head.repo else None,
        changed_files=[],
        total_additions=0,
        total_deletions=0,
        total_changed_files=0,
    )
    result = ReviewCompletion(
        risk="HIGH",
        risk_score=4.5,
        recommendation="REQUEST_CHANGES",
        summary="Synthetic persistence demo. This result was not generated by an AI review.",
        findings=[
            FindingInput(
                agent_type="security",
                file_path="demo/users.py",
                line_number=8,
                severity="HIGH",
                title="Synthetic example: parameterize user lookup",
                description="Example only: user input is interpolated into a SQL query.",
                suggestion="Use bound query parameters.",
                confidence=0.9,
            )
        ],
    )
    engine = build_engine(get_settings())
    try:
        async with build_session_factory(engine).begin() as session:
            store = ReviewRepository(session)
            review = await store.create_review(job, context)
            if review.status == ReviewStatus.QUEUED:
                await store.mark_processing(review.id)
                await store.complete_review(review.id, result)
        print(f"Synthetic review: {job.review_id}")
        print(f"GET /reviews/{job.review_id}")
        print("GET /repositories/octocat/hello-world/reviews")
    finally:
        await engine.dispose()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()
    sample = Path(__file__).resolve().parents[1] / "examples/pull_request.opened.json"
    webhook = PullRequestWebhook.model_validate_json(sample.read_bytes())
    asyncio.run(seed(webhook))


if __name__ == "__main__":
    main()
